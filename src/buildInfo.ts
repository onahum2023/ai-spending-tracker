// Injected at build time by vite.config.ts (see `define`). Also set when tests run.
declare const __APP_VERSION__: string;
declare const __APP_COMMIT__: string;
declare const __APP_BUILD_DATE__: string;
declare const __APP_LICENSE__: string;

export interface BuildInfo {
  /** From package.json. */
  version: string;
  /** Short commit hash of this build, or empty when unknown. */
  commit: string;
  /** Day this build was made, YYYY-MM-DD. */
  date: string;
  /** From package.json, or empty until a license has been chosen. */
  license: string;
}

export const BUILD_INFO: BuildInfo = {
  version: __APP_VERSION__,
  commit: __APP_COMMIT__,
  date: __APP_BUILD_DATE__,
  license: __APP_LICENSE__,
};

/** Where the full license texts of the bundled libraries are served from (generated by `npm run licenses`). */
export const THIRD_PARTY_NOTICES_URL = `${import.meta.env.BASE_URL}third-party-notices.txt`;
